#!/usr/bin/env node
// Generates src/data/legalSource.js from the three repo-root markdown files
// (RootSystems_Terms_of_Service.md / _Privacy_Policy.md / _Refund_Policy.md).
//
// Why this exists: src/utils/markdown.js originally read those .md files
// straight off disk at request time via fs.readFileSync(path.join(__dirname,
// "..", "..", filename)). That works in local dev and on a plain Node host,
// but on this site's actual production host (Vercel), the serverless
// function bundle is built from static analysis of require()/fs calls
// ("file tracing") - and a runtime fs.readFileSync of a loose repo-root file
// reached through a couple of layers of indirection (siteController.js's
// legalPage() closes over a filename string, passed down into
// loadLegalDoc()) does not get picked up by that trace. Confirmed live: the
// three .md files are committed to git and present in the repo Vercel builds
// from, the CSS/JS from the exact same commits IS live, but /terms /privacy
// /refund were still rendering the "not published yet" placeholder in
// production - i.e. fs.existsSync(filePath) was false at runtime specifically
// for these three files, nothing else.
//
// Fix: commit a plain JS module (require()'d normally, always traced
// correctly by any bundler) holding the same content, generated from the .md
// files by this script, and have markdown.js prefer that module over a live
// fs read. Source of truth for editing stays the .md files - a non-technical
// editor still just edits those - this script re-syncs the committed JS
// module afterward. Run manually (`npm run build:legal`) after editing any
// of the three .md files, then commit both the .md change and the
// regenerated src/data/legalSource.js together.
const fs = require("fs");
const path = require("path");

const FILES = [
  "RootSystems_Terms_of_Service.md",
  "RootSystems_Privacy_Policy.md",
  "RootSystems_Refund_Policy.md",
];

const repoRoot = path.join(__dirname, "..");
const outPath = path.join(repoRoot, "src", "data", "legalSource.js");

const entries = FILES.map((filename) => {
  const filePath = path.join(repoRoot, filename);
  if (!fs.existsSync(filePath)) {
    console.warn(`[build-legal-data] ${filename} not found at repo root - skipping (loadLegalDoc will fall back to the placeholder notice for this one).`);
    return null;
  }
  const raw = fs.readFileSync(filePath, "utf8");
  return `  ${JSON.stringify(filename)}: ${JSON.stringify(raw)},`;
}).filter(Boolean);

const header = `// GENERATED by scripts/build-legal-data.js from the .md files at the repo
// root - do not hand-edit. Re-run "npm run build:legal" after changing any
// of RootSystems_Terms_of_Service.md / RootSystems_Privacy_Policy.md /
// RootSystems_Refund_Policy.md, then commit both together. See that
// script's header comment for why this exists (Vercel file-tracing).
module.exports = {
`;

fs.writeFileSync(outPath, header + entries.join("\n") + "\n};\n");
console.log(`[build-legal-data] Wrote ${outPath} (${entries.length}/${FILES.length} files).`);
